const assert = require('node:assert/strict');
const fs = require('node:fs');
const ts = require('typescript');
const source = fs.readFileSync('artifacts/cmms/src/lib/equipment-pagination.ts', 'utf8');
const compiled = ts.transpileModule(source, { compilerOptions: { module: ts.ModuleKind.CommonJS } }).outputText;
const exportsObject = {};
new Function('exports', compiled)(exportsObject);
const paginate = exportsObject.paginateEquipmentRows;
const row = (height, heading = false) => ({ height, heading });
assert.deepEqual(paginate([row(30), row(20, true), row(30)], 100, 20), [[0, 1, 2]]);
assert.deepEqual(paginate([row(65), row(10, true), row(30)], 100, 10), [[0], [1, 2]]);
assert.deepEqual(paginate([row(40), row(40)], 100, 25), [[0], [1]]);
assert.deepEqual(paginate([row(80), row(10, true), row(10, true), row(20)], 100, 10), [[0], [1, 2, 3]]);
const many = Array.from({ length: 30 }, () => row(30));
const pages = paginate(many, 100, 20);
assert.equal(pages.length, 11);
assert.deepEqual(pages.flat(), many.map((_, index) => index));
assert.ok(pages.every((page, index) => page.length * 30 + (index === pages.length - 1 ? 20 : 0) <= 100));
assert.deepEqual(paginate([], 100, 20), []);
console.log('Equipment pagination: 6 checks passed');
